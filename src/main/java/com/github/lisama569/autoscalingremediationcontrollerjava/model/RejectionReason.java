package com.github.lisama569.autoscalingremediationcontrollerjava.model;

/** 所有可区分的拒绝/未执行原因，禁止以模糊错误表达。 */
public enum RejectionReason {
    WORKLOAD_NOT_REGISTERED,
    INVALID_POLICY,
    POLICY_VERSION_CONFLICT,
    MISSING_POLICY,
    MISSING_LOAD_OBSERVATION,
    STALE_LOAD_OBSERVATION,
    /** 扩容意向合法，但全局共享实例容量已满（或被 FIFO 队列前置等待者占用），本次未扩成。 */
    INSUFFICIENT_GLOBAL_CAPACITY,
    COOLDOWN_ACTIVE,
    REMEDIATION_DISABLED,
    INSTANCE_NOT_FOUND,
    INSTANCE_HEALTHY,
    DUPLICATE_REMEDIATION,
    REMEDIATION_CONCURRENCY_LIMIT,
    FAILURE_BUDGET_EXHAUSTED,
    REMEDIATION_COOLDOWN_ACTIVE,
    ILLEGAL_ARGUMENT
}
