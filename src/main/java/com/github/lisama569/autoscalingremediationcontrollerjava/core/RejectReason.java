package com.github.lisama569.autoscalingremediationcontrollerjava.core;

/**
 * 拒绝/终止原因。类别前缀：
 * POLICY_* 非法策略；OBS_* 观测缺失或过期；SCALE_* 伸缩判定；
 * REM_* 修复拒绝；REPAIR_* 修复终态。
 */
public enum RejectReason {
    WORKLOAD_NOT_FOUND,
    WORKLOAD_ALREADY_EXISTS,
    POLICY_INVALID,
    POLICY_VERSION_STALE,
    OBSERVATION_MISSING,
    OBSERVATION_STALE,
    OBSERVATION_DUPLICATE,
    SCALE_IN_COOLDOWN,
    SCALE_AT_MIN_REPLICAS,
    SCALE_AT_MAX_REPLICAS,
    SCALE_IN_PROGRESS,
    REMEDIATION_DISABLED,
    REM_ALREADY_QUEUED,
    REM_ALREADY_IN_PROGRESS,
    REM_NO_UNHEALTHY_INSTANCE,
    REM_IN_REMEDIATION_COOLDOWN,
    REM_QUEUED,
    REM_CONCURRENCY_LIMITED,
    REM_FAILURE_BUDGET_EXHAUSTED,
    REPAIR_TIMEOUT,
    REPAIR_FAILED,
    REPAIR_ATTEMPTS_EXHAUSTED,
    REPAIR_INSTANCE_GONE,
    NO_SCALE_NEEDED,
    NO_QUEUED_TASK,
    OK
}
